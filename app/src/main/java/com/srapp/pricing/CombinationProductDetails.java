package com.srapp.pricing;

public class CombinationProductDetails {
    private String special_price;
    private String category_price;
    private String producct_id;
    private String product_com_id;
    private String price;

    public String getProducct_id() {
        return producct_id;
    }

    public void setProducct_id(String producct_id) {
        this.producct_id = producct_id;
    }

    public String getProduct_com_id() {
        return product_com_id;
    }

    public void setProduct_com_id(String product_com_id) {
        this.product_com_id = product_com_id;
    }

    public String getPrice() {
        return price;
    }

    public void setPrice(String price) {
        this.price = price;
    }

    public String getSpecial_price() {
        return special_price;
    }

    public void setSpecial_price(String special_price) {
        this.special_price = special_price;
    }

    public String getCategory_price() {
        return category_price;
    }

    public void setCategory_price(String category_price) {
        this.category_price = category_price;
    }



}

